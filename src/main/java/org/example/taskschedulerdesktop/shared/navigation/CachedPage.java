package org.example.taskschedulerdesktop.shared.navigation;

import org.example.taskschedulerdesktop.shared.ui.Shutdownable;

/**
 * Раздел меню, который не создаётся заново при каждом переходе. Первое построение экрана (стили и
 * раскладка таблиц и карточек) занимает до нескольких сотен миллисекунд, поэтому готовый экран
 * сохраняется: при уходе раздел ставится на паузу, при возврате показывается сразу и в том же виде
 * (с теми же фильтрами и прокруткой).
 * <p>
 * На паузе раздел не слушает изменения данных, чтобы не перестраиваться в фоне. При возврате он
 * перечитывает данные, только если за это время что-то изменилось.
 */
public interface CachedPage extends Shutdownable {

    /** Раздел скрыт: перестать слушать изменения данных. */
    void pause();

    /**
     * Раздел снова на экране: слушать изменения данных.
     *
     * @param dataChanged менялись ли задачи, проекты или сотрудники, пока раздел был скрыт
     */
    void resume(boolean dataChanged);
}
